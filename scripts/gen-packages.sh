#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
out=iso/profile/packages.x86_64
mkdir -p "$(dirname "$out")"
{
  echo "# GENERATED by scripts/gen-packages.sh - edit packages/*.txt instead"
  # shellcheck disable=SC2002
  cat packages/*.txt 2>/dev/null | sed 's/#.*//' | awk 'NF {print $1}' | sort -u
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
